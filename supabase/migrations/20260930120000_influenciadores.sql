-- Campos null = "não alterar". String vazia vinda do formulário = limpar o campo.
create function public.clube_atualizar_influenciadora(
  p_id uuid,
  p_password text,
  p_nome text default null,
  p_unidade text default null,
  p_unidades_inclusas text[] default null,
  p_formato_parceria text default null,
  p_status_parceria text default null,
  p_codigo_cupom text default null,
  p_status_cupom text default null,
  p_data_inicio text default null,
  p_data_validade text default null,
  p_data_encerramento_parceria text default null,
  p_instagram text default null,
  p_contato text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
begin
  if not clube_check_admin(p_password) then
    return jsonb_build_object('success', false, 'message', 'Acesso não autorizado.');
  end if;
  if p_nome is not null and trim(p_nome) = '' then
    return jsonb_build_object('success', false, 'message', 'O nome não pode ficar vazio.');
  end if;

  update clube_influenciadoras set
    nome = coalesce(trim(p_nome), nome),
    unidade = case when p_unidade is null then unidade else nullif(p_unidade, '') end,
    unidades_inclusas = coalesce(p_unidades_inclusas, unidades_inclusas),
    formato_parceria = case when p_formato_parceria is null then formato_parceria else nullif(p_formato_parceria, '') end,
    status_parceria = case when p_status_parceria is null then status_parceria else nullif(p_status_parceria, '') end,
    codigo_cupom = case when p_codigo_cupom is null then codigo_cupom else nullif(trim(p_codigo_cupom), '') end,
    status_cupom = case when p_status_cupom is null then status_cupom else nullif(p_status_cupom, '') end,
    data_inicio = case when p_data_inicio is null then data_inicio else nullif(p_data_inicio, '')::date end,
    data_validade = case when p_data_validade is null then data_validade else nullif(p_data_validade, '')::date end,
    data_encerramento_parceria = case when p_data_encerramento_parceria is null then data_encerramento_parceria
                                      else nullif(p_data_encerramento_parceria, '')::date end,
    instagram = case when p_instagram is null then instagram else nullif(p_instagram, '') end,
    contato = case when p_contato is null then contato else nullif(p_contato, '') end,
    updated_at = now()
  where id = p_id;

  if not found then
    return jsonb_build_object('success', false, 'message', 'Influenciadora não encontrada.');
  end if;
  return jsonb_build_object('success', true, 'message', 'Atualizado com sucesso!');
end;
$$;

create function public.clube_adicionar_unidade(p_nome text, p_uf text, p_password text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
begin
  if not clube_check_admin(p_password) then
    return jsonb_build_object('success', false, 'message', 'Acesso não autorizado.');
  end if;
  if p_nome is null or trim(p_nome) = '' then
    return jsonb_build_object('success', false, 'message', 'Informe o nome da unidade.');
  end if;
  if exists (select 1 from unidades where lower(nome) = lower(trim(p_nome))) then
    return jsonb_build_object('success', false, 'message', 'Essa unidade já está cadastrada.');
  end if;
  insert into unidades (nome, uf) values (trim(p_nome), nullif(upper(trim(p_uf)), ''));
  return jsonb_build_object('success', true, 'message', 'Unidade "' || trim(p_nome) || '" adicionada.');
end;
$$;

create function public.clube_remover_unidade(p_nome text, p_password text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
begin
  if not clube_check_admin(p_password) then
    return jsonb_build_object('success', false, 'message', 'Acesso não autorizado.');
  end if;
  delete from unidades where nome = p_nome;
  if not found then
    return jsonb_build_object('success', false, 'message', 'Unidade não encontrada.');
  end if;
  return jsonb_build_object('success', true, 'message', 'Unidade removida.');
end;
$$;

create function public.clube_adicionar_inauguracao(
  p_estabelecimento text, p_data_inauguracao date, p_uf text, p_password text
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
begin
  if not clube_check_admin(p_password) then
    return jsonb_build_object('ok', false, 'message', 'Acesso não autorizado.');
  end if;
  if p_estabelecimento is null or trim(p_estabelecimento) = '' or p_data_inauguracao is null then
    return jsonb_build_object('ok', false, 'message', 'Preencha estabelecimento e data.');
  end if;
  insert into inauguracoes (estabelecimento, data_inauguracao, uf)
  values (trim(p_estabelecimento), p_data_inauguracao, nullif(upper(trim(p_uf)), ''));
  return jsonb_build_object('ok', true, 'message', 'Inauguração adicionada.');
end;
$$;

create function public.clube_atualizar_inauguracao(
  p_id bigint,
  p_password text,
  p_estabelecimento text default null,
  p_data_inauguracao text default null,
  p_uf text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
begin
  if not clube_check_admin(p_password) then
    return jsonb_build_object('ok', false, 'message', 'Acesso não autorizado.');
  end if;
  update inauguracoes set
    estabelecimento = coalesce(nullif(trim(p_estabelecimento), ''), estabelecimento),
    data_inauguracao = case when p_data_inauguracao is null then data_inauguracao
                            else nullif(p_data_inauguracao, '')::date end,
    uf = case when p_uf is null then uf else nullif(upper(trim(p_uf)), '') end
  where id = p_id;
  if not found then
    return jsonb_build_object('ok', false, 'message', 'Inauguração não encontrada.');
  end if;
  return jsonb_build_object('ok', true, 'message', 'Inauguração atualizada.');
end;
$$;

