create function public.clube_check_admin(p_password text)
returns boolean
language sql
stable
security definer
set search_path = public, extensions
as $$
  select coalesce(
    (select senha_hash = extensions.crypt(p_password, senha_hash) from clube_admin_config where id = 1),
    false
  ) and p_password is not null;
$$;

create function public.clube_trocar_senha(p_senha_atual text, p_senha_nova text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
begin
  if not clube_check_admin(p_senha_atual) then
    return jsonb_build_object('success', false, 'message', 'Senha atual incorreta.');
  end if;
  if p_senha_nova is null or length(p_senha_nova) < 8 then
    return jsonb_build_object('success', false, 'message', 'A nova senha precisa ter pelo menos 8 caracteres.');
  end if;
  update clube_admin_config
     set senha_hash = extensions.crypt(p_senha_nova, extensions.gen_salt('bf')),
         atualizado_em = now()
   where id = 1;
  return jsonb_build_object('success', true, 'message', 'Senha alterada.');
end;
$$;

create function public.clube_listar_solicitacoes_pendentes(p_password text)
returns setof public.clube_solicitacoes
language plpgsql
stable
security definer
set search_path = public, extensions
as $$
begin
  if not clube_check_admin(p_password) then
    raise exception 'Acesso não autorizado.';
  end if;
  return query
    select * from clube_solicitacoes
     where status_solicitacao = 'pendente'
     order by created_at;
end;
$$;

create function public.clube_aprovar_solicitacao(p_id uuid, p_password text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_row clube_solicitacoes;
  v_extras text[];
begin
  if not clube_check_admin(p_password) then
    return jsonb_build_object('success', false, 'message', 'Acesso não autorizado.');
  end if;

  select * into v_row from clube_solicitacoes where id = p_id;
  if not found then
    return jsonb_build_object('success', false, 'message', 'Solicitação não encontrada.');
  end if;
  if v_row.status_solicitacao = 'aprovado' then
    return jsonb_build_object('success', false, 'message', 'Essa solicitação já foi aprovada anteriormente.');
  end if;

  v_extras := case
    when v_row.outras_unidades is not null and length(trim(v_row.outras_unidades)) > 0
      then (select array_agg(trim(u)) from unnest(string_to_array(v_row.outras_unidades, ',')) as u where trim(u) <> '')
    else '{}'::text[]
  end;

  insert into clube_influenciadoras
    (nome, unidade, unidades_inclusas, formato_parceria, status_parceria, codigo_cupom, status_cupom,
     data_inicio, data_validade, data_encerramento_parceria, instagram, contato)
  values
    (v_row.nome_influenciador, v_row.unidade, coalesce(v_extras, '{}'), coalesce(v_row.formato_parceria_sugerido, 'clube'),
     coalesce(v_row.status_parceria_sugerido, 'ativa'),
     nullif(trim(coalesce(v_row.codigo_cupom_sugerido, '')), ''),
     'ativa', current_date, v_row.data_validade_sugerida, v_row.data_encerramento_parceria_sugerida,
     v_row.instagram, v_row.contato);

  update clube_solicitacoes set status_solicitacao = 'aprovado' where id = p_id;

  return jsonb_build_object(
    'success', true,
    'message', case
      when v_row.codigo_cupom_sugerido is not null and trim(v_row.codigo_cupom_sugerido) <> ''
        then '✅ Cadastro de "' || v_row.nome_influenciador || '" aprovado com o cupom ' || v_row.codigo_cupom_sugerido || '!'
      else '✅ Cadastro de "' || v_row.nome_influenciador || '" aprovado! Não esqueça de preencher o código do cupom na edição da influenciadora.'
    end
  );
end;
$$;

