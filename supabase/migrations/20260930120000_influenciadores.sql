-- ============================================================
-- Views
-- Juntam consumo_cupons com clube_influenciadoras pelo código exato do cupom.
-- Um código cadastrado em duas influenciadoras conta o consumo nas duas —
-- mesmo comportamento das views originais.
-- ============================================================

create view public.clube_faturamento_por_influenciadora as
select
  i.id,
  i.nome,
  i.unidade,
  i.unidades_inclusas,
  i.codigo_cupom,
  i.status_parceria,
  i.status_cupom,
  i.data_validade,
  coalesce(sum(c.valor_liquido), 0) as receita_total,
  count(distinct c.comanda) as atendimentos_total,
  coalesce(sum(c.valor_liquido) filter (where c.data_hora_atendimento >= now() - interval '30 days'), 0)
    as receita_ultimos_30_dias,
  count(distinct c.comanda) filter (where c.data_hora_atendimento >= now() - interval '30 days')
    as atendimentos_ultimos_30_dias,
  max(c.data_hora_atendimento) as ultima_utilizacao
from public.clube_influenciadoras i
left join public.consumo_cupons c on c.codigo_cupom = i.codigo_cupom
group by i.id;

create view public.clube_cupons_mensal as
with uso as (
  select
    date_trunc('month', c.data_hora_atendimento at time zone 'UTC')::date as mes,
    count(distinct c.codigo_cupom) as cupons_utilizados_distintos,
    count(distinct c.comanda) as atendimentos,
    round(sum(c.valor_liquido), 2) as receita
  from public.consumo_cupons c
  join public.clube_influenciadoras i on i.codigo_cupom = c.codigo_cupom
  where c.data_hora_atendimento is not null
  group by 1
)
select
  u.mes,
  (select count(*) from public.clube_influenciadoras i
    where i.codigo_cupom is not null
      and i.data_inicio < (u.mes + interval '1 month')) as cupons_emitidos_acumulado,
  u.cupons_utilizados_distintos,
  u.atendimentos,
  u.receita
from uso u
order by u.mes;

create view public.clube_status_cupons as
with cad as (
  select i.codigo_cupom,
         exists (select 1 from public.consumo_cupons c where c.codigo_cupom = i.codigo_cupom) as convertido
  from public.clube_influenciadoras i
  where i.codigo_cupom is not null
)
select
  (select count(*) from cad) as cupons_cadastrados,
  (select count(*) from cad where convertido) as cupons_convertidos,
  (select count(*) from cad where not convertido) as cupons_nao_convertidos,
  round(100.0 * (select count(*) from cad where convertido) / nullif((select count(*) from cad), 0), 1)
    as taxa_conversao_pct,
  (select coalesce(round(sum(c.valor_liquido), 2), 0)
     from public.consumo_cupons c
     join public.clube_influenciadoras i on i.codigo_cupom = c.codigo_cupom) as receita_total;

grant select on public.clube_faturamento_por_influenciadora, public.clube_cupons_mensal,
  public.clube_status_cupons to anon, authenticated;

